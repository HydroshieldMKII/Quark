// Package extract collects strings marked with T, Tf, N and M from Go
// sources and renders a gettext template. Used by tools/i18n-extract and by
// the i18n tests, which check that the committed template is current.
package extract

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// Message is one translatable string.
type Message struct {
	ID, Plural string
	Refs       []string
	Format     bool
}

// Extract walks root and returns the messages, sorted by ID.
func Extract(root string) ([]Message, error) {
	byID := map[string]*Message{}
	fset := token.NewFileSet()
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "bin", "build-dir", ".flatpak-builder", "testdata", "tools":
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			name := ""
			switch fn := call.Fun.(type) {
			case *ast.Ident:
				name = fn.Name
			case *ast.SelectorExpr:
				name = fn.Sel.Name
			}
			lit := func(i int) (string, bool) {
				if i >= len(call.Args) {
					return "", false
				}
				b, ok := call.Args[i].(*ast.BasicLit)
				if !ok || b.Kind != token.STRING {
					return "", false
				}
				s, err := strconv.Unquote(b.Value)
				return s, err == nil
			}
			pos := fset.Position(call.Pos())
			rel, rerr := filepath.Rel(root, pos.Filename)
			if rerr != nil {
				rel = pos.Filename
			}
			ref := fmt.Sprintf("%s:%d", filepath.ToSlash(rel), pos.Line)
			add := func(id, plural string, format bool) {
				if id == "" {
					return
				}
				m := byID[id]
				if m == nil {
					m = &Message{ID: id}
					byID[id] = m
				}
				if plural != "" {
					m.Plural = plural
				}
				m.Format = m.Format || format || strings.Contains(id, "%")
				m.Refs = append(m.Refs, ref)
			}
			switch name {
			case "T", "M":
				if s, ok := lit(0); ok {
					add(s, "", false)
				}
			case "Tf":
				if s, ok := lit(0); ok {
					add(s, "", true)
				}
			case "N":
				s, ok1 := lit(0)
				p, ok2 := lit(1)
				if ok1 && ok2 {
					add(s, p, true)
				}
			}
			return true
		})
		return nil
	})
	if err != nil {
		return nil, err
	}
	out := make([]Message, 0, len(byID))
	for _, m := range byID {
		out = append(out, *m)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out, nil
}

func quote(s string) string { return strconv.Quote(s) }

// Template renders a .pot file.
func Template(msgs []Message) string {
	var b strings.Builder
	b.WriteString("# Quark translation template. Generated by tools/i18n-extract; do not edit.\n")
	b.WriteString("msgid \"\"\nmsgstr \"\"\n\"Content-Type: text/plain; charset=UTF-8\\n\"\n\"Plural-Forms: nplurals=2; plural=(n != 1);\\n\"\n\n")
	for _, m := range msgs {
		for _, r := range m.Refs {
			b.WriteString("#: " + r + "\n")
		}
		if m.Format {
			b.WriteString("#, c-format\n")
		}
		b.WriteString("msgid " + quote(m.ID) + "\n")
		if m.Plural != "" {
			b.WriteString("msgid_plural " + quote(m.Plural) + "\nmsgstr[0] \"\"\nmsgstr[1] \"\"\n\n")
		} else {
			b.WriteString("msgstr \"\"\n\n")
		}
	}
	return b.String()
}
